#!/usr/bin/env node
// Generates the cordis patch that enables @aizu/adapter-dsh with one exact
// assignment. Every value comes from the operator; nothing is read from the
// environment or the repository. Output goes to stdout.

const IDENTIFIER = /^[A-Za-z0-9][A-Za-z0-9._:-]{0,127}$/;

function usage(message) {
  if (message) process.stderr.write(`make-patch: ${message}\n`);
  process.stderr.write(
    'usage: make-patch.mjs --binary <path> --state <dir> --event-id <id> --workflow-id <id> --assignment-id <id> --role <implementation|review> --revision <id> [--timeout-ms <n>]\n',
  );
  process.exit(2);
}

const args = process.argv.slice(2);
const options = {};
for (let i = 0; i < args.length; i += 2) {
  const key = args[i];
  const value = args[i + 1];
  if (!key?.startsWith('--') || value === undefined) usage(`bad argument ${key}`);
  options[key.slice(2)] = value;
}

const required = ['binary', 'state', 'event-id', 'workflow-id', 'assignment-id', 'role', 'revision'];
for (const key of required) if (!options[key]) usage(`missing --${key}`);
for (const key of ['event-id', 'workflow-id', 'assignment-id', 'revision']) {
  if (!IDENTIFIER.test(options[key])) usage(`--${key} must match ${IDENTIFIER}`);
}
if (options.role !== 'implementation' && options.role !== 'review') usage('--role must be implementation or review');
const timeoutMs = Number(options['timeout-ms'] ?? 15000);
if (!Number.isInteger(timeoutMs) || timeoutMs <= 0) usage('--timeout-ms must be a positive integer');

const yamlString = (value) => JSON.stringify(String(value));
process.stdout.write(`# Generated by experiments/dsh-live-smoke/make-patch.mjs. Keep outside the repository.
- insert:
    - id: aizu-workflow-signal
      name: "@aizu/adapter-dsh"
      config:
        binary: ${yamlString(options.binary)}
        stateDir: ${yamlString(options.state)}
        timeoutMs: ${timeoutMs}
        eventId: ${yamlString(options['event-id'])}
        workflowId: ${yamlString(options['workflow-id'])}
        assignmentId: ${yamlString(options['assignment-id'])}
        role: ${options.role}
        artifactRevision: ${yamlString(options.revision)}
`);
